-- Tabel utama alumni
create table if not exists public.alumni (
  id bigint generated by default as identity primary key,
  full_name text not null check (char_length(full_name) between 2 and 120),
  gender text not null check (gender in ('Laki-laki', 'Perempuan')),
  entry_year integer,
  graduation_year integer,
  whatsapp text not null check (char_length(whatsapp) between 6 and 25),
  city text,
  education text,
  occupation text,
  message text,
  consent boolean not null default false check (consent = true),
  status text not null default 'pending' check (status in ('pending', 'verified')),
  created_at timestamptz not null default now()
);

-- Daftar akun yang boleh mengakses dashboard admin.
create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

alter table public.alumni enable row level security;
alter table public.admin_users enable row level security;

-- Publik boleh mengirim data baru, tetapi hanya dengan status pending.
drop policy if exists "public can submit alumni" on public.alumni;
create policy "public can submit alumni"
on public.alumni for insert
to anon, authenticated
with check (status = 'pending' and consent = true);

-- Hanya admin terdaftar yang boleh membaca data alumni.
drop policy if exists "admins can read alumni" on public.alumni;
create policy "admins can read alumni"
on public.alumni for select
to authenticated
using (
  exists (select 1 from public.admin_users au where au.user_id = auth.uid())
);

-- Hanya admin terdaftar yang boleh mengubah data alumni.
drop policy if exists "admins can update alumni" on public.alumni;
create policy "admins can update alumni"
on public.alumni for update
to authenticated
using (
  exists (select 1 from public.admin_users au where au.user_id = auth.uid())
)
with check (
  exists (select 1 from public.admin_users au where au.user_id = auth.uid())
);

-- Hanya admin terdaftar yang boleh menghapus data alumni.
drop policy if exists "admins can delete alumni" on public.alumni;
create policy "admins can delete alumni"
on public.alumni for delete
to authenticated
using (
  exists (select 1 from public.admin_users au where au.user_id = auth.uid())
);

-- Pengguna hanya dapat melihat baris admin miliknya sendiri.
drop policy if exists "admins can read own admin row" on public.admin_users;
create policy "admins can read own admin row"
on public.admin_users for select
to authenticated
using (user_id = auth.uid());

